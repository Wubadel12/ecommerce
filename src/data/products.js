// Images live in public/images/products/<slug>/1.<ext>, 2.<ext>, 3.<ext>.
// The repo ships generated placeholders (.svg). Swap in real photos and change this to 'webp' or 'jpg'.
const IMAGE_EXTENSION = 'svg'
const IMAGES_PER_PRODUCT = 3

const COLOR = {
  black: { name: 'Black', hex: '#1b1d21' },
  graphite: { name: 'Graphite', hex: '#4a4f57' },
  silver: { name: 'Silver', hex: '#c4c8cf' },
  white: { name: 'White', hex: '#f3f4f6' },
  blue: { name: 'Blue', hex: '#2f5fc4' },
  green: { name: 'Green', hex: '#3f7a5a' },
  red: { name: 'Red', hex: '#b83232' },
  tan: { name: 'Tan', hex: '#b88a5a' },
}

function buildImages(slug) {
  return Array.from(
    { length: IMAGES_PER_PRODUCT },
    (_, index) => `/images/products/${slug}/${index + 1}.${IMAGE_EXTENSION}`,
  )
}

function createProduct(product) {
  return {
    oldPrice: null,
    colors: [],
    sizes: [],
    featured: false,
    bestseller: false,
    newArrival: false,
    ...product,
    discount: calculateDiscountPercent(product.price, product.oldPrice),
    images: buildImages(product.slug),
  }
}

